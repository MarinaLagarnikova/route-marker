/**
 * Ступени слоя «Интересное» по зуму.
 *
 * Механика komoot: не выключатель, а ранжирование — чем дальше отъехал, тем
 * меньше объектов на экране. На обзорном зуме слой молчит целиком, чтобы трек
 * читался как трек; дальше объекты проступают по важности категории.
 *
 * ВАЖНО: пороги обязаны быть целыми. MapLibre пересчитывает ['zoom'] внутри
 * filter только на целых зумах, поэтому порог 14.5 просто не сработает.
 */
export interface PoiZoomStep {
  /** С этого зума и выше действует порог ниже. */
  zoom: number
  /** Показываем категории с приоритетом не больше этого (см. CATEGORY_PRIORITY). */
  maxPriority: number
}

export const POI_ZOOM_STEPS: readonly PoiZoomStep[] = [
  { zoom: 13, maxPriority: 3 }, // вода, ночёвка, осторожно
  { zoom: 15, maxPriority: 6 }, // + снабжение, посмотреть, рукотворное
]

/**
 * Фотографии приходят вместе с полным составом объектов, а не ступенью позже:
 * на 16 до них пришлось бы домотать специально, и слой бы их потерял. На обзоре
 * их всё равно нет — плашка крупная и закрывает трек.
 */
export const PHOTO_MIN_ZOOM = 15

/** Наибольший приоритет, который виден на этом зуме. Ноль — не видно никого. */
export function maxPriorityAtZoom(zoom: number): number {
  let limit = 0
  for (const step of POI_ZOOM_STEPS) {
    if (zoom >= step.zoom) limit = step.maxPriority
  }
  return limit
}
