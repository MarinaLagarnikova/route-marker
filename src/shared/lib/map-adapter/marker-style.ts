/**
 * Общий вид маркеров карты — контрольных точек, меток объектов и плашек
 * фотографий. Рисуются они тремя разными способами (CSS, SVG, canvas), и без
 * общих величин расходятся: разная тень читается как разная высота над картой,
 * разная окантовка — как разная принадлежность.
 *
 * Величины держим в CSS-пикселях, каждый способ пересчитывает их у себя.
 */

/**
 * Толщина окантовки: белая рамка у фотографии, белый кант у метки, кольцо у
 * контрольной точки. Канон — рамка фотографии, она самая заметная.
 */
export const MARKER_BORDER = 2.5

/** Тень. Канон — запись контрольной точки, она появилась первой. */
export const MARKER_SHADOW = {
  offsetY: 1,
  /** Радиус размытия в терминах CSS box-shadow. */
  blur: 4,
  opacity: 0.2,
} as const

export const MARKER_SHADOW_COLOR = `rgba(0,0,0,${MARKER_SHADOW.opacity})`

export const MARKER_SHADOW_CSS =
  `0 ${MARKER_SHADOW.offsetY}px ${MARKER_SHADOW.blur}px ${MARKER_SHADOW_COLOR}`

/**
 * Сигма гауссианы для SVG `feDropShadow`.
 *
 * По спецификации CSS радиус размытия равен удвоенному стандартному отклонению,
 * поэтому пополам. Без пересчёта тень у метки выходила вдвое туже, чем у точки.
 */
export const MARKER_SHADOW_SIGMA = MARKER_SHADOW.blur / 2
